test_that("write_tex_macros formats numbers consistently", {
  path <- withr::local_tempfile(fileext = ".tex")
  write_tex_macros(list(nObs = 31000, tvEffect = -0.04567, share = 0.5, estimator = "TWFE"), path)
  lines <- readLines(path)
  expect_match(lines[1], "^% Generated by write_tex_macros")
  expect_equal(lines[-1], c(
    "\\newcommand{\\nObs}{31{,}000}",
    "\\newcommand{\\tvEffect}{\\ensuremath{-}0.05}",
    "\\newcommand{\\share}{0.50}",
    "\\newcommand{\\estimator}{TWFE}"
  ))
})

test_that("write_tex_macros respects digits", {
  path <- withr::local_tempfile(fileext = ".tex")
  write_tex_macros(list(bigNumber = 1234.5678), path, digits = 3)
  expect_equal(readLines(path)[2], "\\newcommand{\\bigNumber}{1{,}234.568}")
})

test_that("write_tex_macros rejects invalid names and values", {
  path <- withr::local_tempfile(fileext = ".tex")
  expect_error(write_tex_macros(list(n_obs = 1), path), "letters only")
  expect_error(write_tex_macros(list(nA = 1, nA = 2), path), "duplicate")
  expect_error(write_tex_macros(list(nObs = NA), path), "non-missing")
  expect_error(write_tex_macros(list(nObs = 1:2), path), "single")
})

test_that("write_tex_macros takes one digits entry per value", {
  path <- withr::local_tempfile(fileext = ".tex")
  write_tex_macros(list(effect = 0.12345, pct = 13.14), path, digits = c(3, 1))
  expect_equal(readLines(path)[2:3],
               c("\\newcommand{\\effect}{0.123}", "\\newcommand{\\pct}{13.1}"))
  expect_error(write_tex_macros(list(a = 1, b = 2, c = 3), path, digits = c(1, 2)), "length 1")
})
